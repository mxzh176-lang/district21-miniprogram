const MONTH_NAMES = ['一月', '二月', '三月', '四月', '五月', '六月', '七月', '八月', '九月', '十月', '十一月', '十二月']

function parseDateText(value) {
  const match = String(value || '').match(/^(\d{4})-(\d{2})-(\d{2})$/)
  if (!match) throw new Error('reference date must use YYYY-MM-DD')
  const year = Number(match[1])
  const month = Number(match[2])
  const day = Number(match[3])
  const date = new Date(Date.UTC(year, month - 1, day))
  if (date.toISOString().slice(0, 10) !== value) throw new Error('reference date is invalid')
  return { year, month, day }
}

function buildMonthlyMeetingTarget(referenceDateText) {
  let { year, month, day } = parseDateText(referenceDateText)
  if (day > 5) {
    month += 1
    if (month > 12) {
      year += 1
      month = 1
    }
  }
  const monthText = String(month).padStart(2, '0')
  return {
    id: `todo_yuanhang_monthly_meeting_${year}_${monthText}`,
    date: `${year}-${monthText}-05`,
    month: `${year}-${monthText}`,
    title: `远航${MONTH_NAMES[month - 1]}例会+联谊`
  }
}

function referenceDateText(referenceDate = new Date()) {
  const year = referenceDate.getFullYear()
  const month = String(referenceDate.getMonth() + 1).padStart(2, '0')
  const day = String(referenceDate.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

function buildUpcomingMonthlyMeetingTask(referenceDate = new Date()) {
  const target = buildMonthlyMeetingTarget(referenceDateText(referenceDate))
  return {
    _id: target.id,
    id: target.id,
    title: target.title,
    description: '系统根据自然月自动生成每月5日例会联谊提醒',
    category: '会议培训',
    date: target.date,
    month: target.month,
    day: '05',
    team: '远航服务队',
    teamId: 'yuanhang',
    organizationId: 'org_team_yuanhang',
    creatorId: 'system_monthly_meeting',
    status: 'pending',
    visible: true,
    visibleToAll: true,
    autoGenerated: true,
    monthlyMeeting: true
  }
}

module.exports = { buildMonthlyMeetingTarget, buildUpcomingMonthlyMeetingTask }
