const HOLIDAYS = [
  { profession: 'teacher', name: '教师节', monthDay: '09-10' },
  { profession: 'nurse', name: '护士节', monthDay: '05-12' },
  { profession: 'doctor', name: '中国医师节', monthDay: '08-19' }
]

function pad(value) {
  return String(value).padStart(2, '0')
}

function upcomingHoliday(monthDay, referenceDate = new Date()) {
  const [month, day] = monthDay.split('-').map(Number)
  const today = new Date(referenceDate.getFullYear(), referenceDate.getMonth(), referenceDate.getDate())
  let date = new Date(today.getFullYear(), month - 1, day)
  if (date < today) date = new Date(today.getFullYear() + 1, month - 1, day)
  return { date, difference: Math.round((date - today) / 86400000) }
}

function buildMemberHolidayTasks(members = [], referenceDate = new Date()) {
  return HOLIDAYS.map((holiday, index) => {
    const names = members.filter(item => item.profession === holiday.profession).map(item => item.name).filter(Boolean)
    const upcoming = upcomingHoliday(holiday.monthDay, referenceDate)
    if (!names.length || upcoming.difference < 0 || upcoming.difference > 30) return null
    const date = `${upcoming.date.getFullYear()}-${pad(upcoming.date.getMonth() + 1)}-${pad(upcoming.date.getDate())}`
    return {
      _id: `todo_member_holiday_${upcoming.date.getFullYear()}_${index + 1}`,
      id: `todo_member_holiday_${upcoming.date.getFullYear()}_${index + 1}`,
      title: `${holiday.name}关怀提醒`,
      description: `关怀成员：${names.join('、')}`,
      category: '生日关爱',
      date,
      month: date.slice(0, 7),
      day: date.slice(8, 10),
      team: '远航服务队',
      teamId: 'yuanhang',
      organizationId: 'org_team_yuanhang',
      creatorId: 'system_member_holiday',
      status: 'pending',
      visible: true,
      visibleToAll: true,
      autoGenerated: true,
      holidayType: holiday.profession,
      memberNames: names
    }
  }).filter(Boolean)
}

module.exports = { HOLIDAYS, buildMemberHolidayTasks }
