function pad(value) {
  return String(value).padStart(2, '0')
}

function dateText(date) {
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
}

function nextBirthdayDate(monthDay, referenceDate = new Date()) {
  const match = String(monthDay || '').match(/^(\d{2})-(\d{2})$/)
  if (!match) return null
  const today = new Date(referenceDate.getFullYear(), referenceDate.getMonth(), referenceDate.getDate())
  let birthday = new Date(today.getFullYear(), Number(match[1]) - 1, Number(match[2]))
  if (birthday < today) birthday = new Date(today.getFullYear() + 1, Number(match[1]) - 1, Number(match[2]))
  return birthday
}

function buildUpcomingBirthdayTasks(birthdays = {}, referenceDate = new Date()) {
  const today = new Date(referenceDate.getFullYear(), referenceDate.getMonth(), referenceDate.getDate())
  return Object.entries(birthdays).map(([name, birthday], index) => {
    const date = nextBirthdayDate(birthday, today)
    const difference = date ? Math.round((date - today) / 86400000) : -1
    if (!date || difference < 0 || difference > 30) return null
    const dateValue = dateText(date)
    return {
      _id: `todo_birthday_${date.getFullYear()}_${index + 1}`,
      id: `todo_birthday_${date.getFullYear()}_${index + 1}`,
      title: `${name}生日关爱`,
      description: '系统根据成员生日提前30天自动生成',
      category: '生日关爱',
      date: dateValue,
      month: dateValue.slice(0, 7),
      day: dateValue.slice(8, 10),
      team: '远航服务队',
      teamId: 'yuanhang',
      organizationId: 'org_team_yuanhang',
      managerId: '',
      creatorId: 'system_birthday',
      status: 'pending',
      visible: true,
      visibleToAll: true,
      birthdayMemberName: name,
      autoGenerated: true
    }
  }).filter(Boolean)
}

module.exports = { nextBirthdayDate, buildUpcomingBirthdayTasks }
