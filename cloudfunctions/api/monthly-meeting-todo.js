const TODO_ORGANIZATION_ID = 'org_team_yuanhang'
const MONTH_NAMES = ['一月', '二月', '三月', '四月', '五月', '六月', '七月', '八月', '九月', '十月', '十一月', '十二月']

function parseDateText(value) {
  const match = String(value || '').match(/^(\d{4})-(\d{2})-(\d{2})$/)
  if (!match) throw new Error('reference date must use YYYY-MM-DD')
  const year = Number(match[1])
  const month = Number(match[2])
  const day = Number(match[3])
  const date = new Date(Date.UTC(year, month - 1, day))
  if (date.toISOString().slice(0, 10) !== value) throw new Error('reference date is invalid')
  return { year, month, day }
}

function buildMonthlyMeetingTarget(referenceDateText) {
  let { year, month, day } = parseDateText(referenceDateText)
  if (day > 5) {
    month += 1
    if (month > 12) {
      year += 1
      month = 1
    }
  }
  const monthText = String(month).padStart(2, '0')
  return {
    id: `todo_yuanhang_monthly_meeting_${year}_${monthText}`,
    date: `${year}-${monthText}-05`,
    month: `${year}-${monthText}`,
    title: `远航${MONTH_NAMES[month - 1]}例会+联谊`
  }
}

function matchesMonthlyMeetingTodo(todo = {}, target = {}) {
  if (todo.organizationId !== TODO_ORGANIZATION_ID || todo.date !== target.date) return false
  return todo.title === '远航第二次例会' || todo.title === target.title
}

function needsCorrection(todo, desired) {
  return Object.keys(desired).some(key => todo[key] !== desired[key])
}

async function ensureMonthlyMeetingTodo(dependencies = {}) {
  const target = buildMonthlyMeetingTarget(dependencies.todayText())
  const tasks = await dependencies.listTasks()
  const existing = tasks.find(task => task.organizationId === TODO_ORGANIZATION_ID && task.id === target.id) ||
    tasks.find(task => matchesMonthlyMeetingTodo(task, target))
  const desired = {
    id: target.id,
    title: target.title,
    category: '会议培训',
    date: target.date,
    organizationId: TODO_ORGANIZATION_ID,
    creatorId: existing && existing.creatorId ? existing.creatorId : 'system_monthly_meeting',
    visible: true,
    visibleToAll: true,
    autoGenerated: true,
    monthlyMeeting: true
  }

  if (existing) {
    if (!needsCorrection(existing, desired)) return { action: 'none', taskId: target.id }
    const update = { ...desired, updatedAt: dependencies.timestamp() }
    await dependencies.updateTask(existing, update)
    await dependencies.writeAudit('update', target.id, update)
    return { action: 'update', taskId: target.id }
  }

  const timestamp = dependencies.timestamp()
  const task = {
    ...desired,
    description: '系统根据自然月自动生成每月5日例会联谊提醒',
    time: '',
    location: '',
    managerId: '',
    status: 'pending',
    createdAt: timestamp,
    updatedAt: timestamp
  }
  await dependencies.createTask(task)
  await dependencies.writeAudit('create', target.id, task)
  return { action: 'create', taskId: target.id }
}

module.exports = {
  TODO_ORGANIZATION_ID,
  buildMonthlyMeetingTarget,
  matchesMonthlyMeetingTodo,
  ensureMonthlyMeetingTodo
}
